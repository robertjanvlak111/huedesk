#!/usr/bin/env python3
"""Generate package/contents/code/Icons.js from the bundled SVG files.

Kirigami.Icon does not apply its `color` to a plain SVG file: the icon renders
as the black silhouette the file describes, which is invisible on a dark card.
So the widget builds each icon at runtime as a data URL with the fill colour
baked in, and this turns the .svg files into the path data it needs.

The .svg files remain the source of truth; CI checks this output is in sync.

    python3 tools/gen_icons.py [--check]
"""

from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ICON_DIR = REPO / "package" / "contents" / "icons"
OUT = REPO / "package" / "contents" / "code" / "Icons.js"
SVG_NS = "http://www.w3.org/2000/svg"


def inner_markup(path: Path) -> str:
    """Return an SVG's children as markup, without the <svg> wrapper."""
    root = ET.parse(path).getroot()
    parts = []
    for child in root:
        raw = ET.tostring(child, encoding="unicode")
        raw = raw.replace(f'xmlns:ns0="{SVG_NS}" ', "").replace("ns0:", "")
        raw = re.sub(r"\s+", " ", raw).strip()
        parts.append(raw)
    return "".join(parts)


def build() -> str:
    icons = {p.stem: inner_markup(p) for p in sorted(ICON_DIR.glob("*.svg"))}
    lines = [
        ".pragma library",
        "",
        "/*",
        " * Icons.js - GENERATED by tools/gen_icons.py. Do not edit.",
        " *",
        " * Source: package/contents/icons/*.svg",
        " *",
        " * Kirigami.Icon ignores its `color` for a plain SVG file, so every",
        " * bundled icon rendered as a black silhouette - invisible on a dark",
        " * card. Building the SVG at runtime with the fill baked in is",
        " * reliable and needs no graphical effects.",
        " */",
        "",
        "var PATHS = {",
    ]
    for name, markup in icons.items():
        lines.append(f"    {json_key(name)}: {js_string(markup)},")
    lines += [
        "};",
        "",
        "/*",
        " * An SVG data URL for `name`, filled with `color` (\"#rrggbb\").",
        " *",
        " * `alpha` is written into the SVG rather than applied as item",
        " * opacity, so callers keep `opacity` free for their own use.",
        " */",
        "function url(name, color, alpha) {",
        "    var body = PATHS[name] || PATHS['bulb'];",
        "    var a = (alpha === undefined || alpha === null) ? 1 : alpha;",
        "    var svg = '<svg xmlns=\"http://www.w3.org/2000/svg\" '",
        "            + 'viewBox=\"0 0 24 24\" fill=\"' + color + '\"'",
        "            + ' fill-opacity=\"' + a + '\">' + body + '</svg>';",
        "    return 'data:image/svg+xml;utf8,' + encodeURIComponent(svg);",
        "}",
        "",
        "function names() {",
        "    return Object.keys(PATHS);",
        "}",
        "",
        "if (typeof module !== 'undefined' && module.exports) {",
        "    module.exports = { PATHS, url, names };",
        "}",
        "",
    ]
    return "\n".join(lines)


def json_key(name: str) -> str:
    return f"'{name}'"


def js_string(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main() -> int:
    generated = build()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != generated:
            print("Icons.js is out of date; run: python3 tools/gen_icons.py",
                  file=sys.stderr)
            return 1
        print(f"Icons.js is in sync ({len(build().splitlines())} lines)")
        return 0
    OUT.write_text(generated)
    count = len(list(ICON_DIR.glob("*.svg")))
    print(f"wrote {OUT.relative_to(REPO)} from {count} svg files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
